from __future__ import annotations

import argparse
import uuid
from typing import Any, Dict

from google.cloud.dialogflowcx_v3 import SessionsClient
from google.cloud.dialogflowcx_v3.types import session

from src.config import DialogflowCXConfig, load_dialogflow_cx_config


def build_sessions_client(
    config: DialogflowCXConfig,
) -> SessionsClient:
    """
    Build a Dialogflow CX SessionsClient.

    The global location uses the default API endpoint.
    Regional agents use a region-specific endpoint.
    """

    client_options = None

    if config.location != "global":
        client_options = {
            "api_endpoint": (
                f"{config.location}-dialogflow.googleapis.com:443"
            )
        }

    return SessionsClient(
        client_options=client_options
    )


def detect_intent_text(
    text: str,
    config: DialogflowCXConfig | None = None,
    session_id: str | None = None,
) -> Dict[str, Any]:
    """
    Send one text utterance to Dialogflow CX.

    A fresh session ID is generated by default so that
    independent evaluation cases do not share state.
    """

    if config is None:
        config = load_dialogflow_cx_config()

    client = build_sessions_client(config)

    if session_id is None:
        session_id = str(uuid.uuid4())

    session_path = client.session_path(
        project=config.project_id,
        location=config.location,
        agent=config.agent_id,
        session=session_id,
    )

    text_input = session.TextInput(
        text=text
    )

    query_input = session.QueryInput(
        text=text_input,
        language_code=config.language_code,
    )

    request = session.DetectIntentRequest(
        session=session_path,
        query_input=query_input,
    )

    response = client.detect_intent(
        request=request
    )

    query_result = response.query_result
    match = query_result.match

    predicted_intent = ""

    if (
        match.intent
        and match.intent.display_name
    ):
        predicted_intent = (
            match.intent.display_name
        )

    current_page = ""

    if query_result.current_page:
        current_page = (
            query_result.current_page.display_name
        )

    response_texts = []

    for message in query_result.response_messages:
        if message.text and message.text.text:
            response_texts.extend(
                message.text.text
            )

    return {
        "text": text,
        "predicted_intent": predicted_intent,
        "confidence": float(
            match.confidence
        ),
        "current_page": current_page,
        "response_text": " ".join(
            response_texts
        ),
        "session_id": session_id,
    }


def main() -> None:
    """
    Command-line entry point for a single
    Dialogflow CX detectIntent request.
    """

    parser = argparse.ArgumentParser(
        description=(
            "Send one text utterance to Dialogflow CX "
            "and inspect the detected intent."
        )
    )

    parser.add_argument(
        "text",
        help="User utterance to send to Dialogflow CX.",
    )

    args = parser.parse_args()

    result = detect_intent_text(
        args.text
    )

    print()
    print("Dialogflow CX detectIntent result")
    print("=" * 40)
    print(
        f"Text: {result['text']}"
    )
    print(
        "Predicted intent: "
        f"{result['predicted_intent'] or 'NO MATCH'}"
    )
    print(
        f"Confidence: {result['confidence']:.4f}"
    )
    print(
        f"Current page: {result['current_page']}"
    )
    print(
        f"Agent response: {result['response_text']}"
    )
    print(
        f"Session ID: {result['session_id']}"
    )


if __name__ == "__main__":
    main()
